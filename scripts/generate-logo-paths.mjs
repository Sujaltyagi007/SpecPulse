import fs from 'node:fs';
const [src, out] = process.argv.slice(2);
const svg = fs.readFileSync(src, 'utf8');
const paths = [...svg.matchAll(/<path[^>]*?fill="([^"]+)"[^>]*?d="([^"]+)"/g)].map((m) => ({ fill: m[1], d: m[2].trim() }));
if (paths.length !== 17) throw new Error(`expected 17 paths, got ${paths.length}`);
const firstX = (d) => Number(d.match(/M\s*([\d.]+)/)[1]);
const height = (d) => { const n = d.match(/-?[\d.]+/g).map(Number).filter((_, i) => i % 2); return Math.round(Math.max(...n) - Math.min(...n)); };

const sub = paths[0].d.split(/(?=M )/).map((s) => s.trim());
const [shield, ...bars] = sub;
bars.sort((a, b) => firstX(a) - firstX(b));

const dots = paths.slice(2, 7).sort((a, b) => firstX(a.d) - firstX(b.d));
const letters = [8, 9, 10, 11, 12, 13, 14, 15, 16].map((i) => paths[i]).sort((a, b) => firstX(a.d) - firstX(b.d));
const navy = (f) => f.includes('1,37,117') || f.includes('Gradient1');

const q = JSON.stringify;
const lines = [
  '// Generated by scripts/generate-logo-paths.mjs from public/brand/specpulse-logo.svg (the official logo); coordinates are unchanged.',
  '// The original draws the bars and arrow as transparent holes; here they are separate shapes so they can animate.',
  '',
  `export const SHIELD = ${q(shield)};`,
  `export const SHIELD_EDGE = ${q(paths[1].d)};`,
  `export const ARROW_BODY = ${q(paths[7].d)};`,
  '',
  '/** Left to right. `dot` is the signal light in the bar\'s ring. */',
  'export const BARS = [',
  ...bars.map((d, i) => `  { d: ${q(d)}, height: ${height(d)}, dot: ${q(dots[i].d)}, dotFill: ${q(dots[i].fill)} },`),
  '];',
  '',
  '/** S P E C P U L S E, left to right; `navy` letters spell SPEC. A `url(#Gradient1)` fill refers to the navy gradient. */',
  'export const LETTERS = [',
  ...letters.map((l) => `  { d: ${q(l.d)}, fill: ${q(l.fill)}, navy: ${navy(l.fill)} },`),
  '];',
  '',
];
fs.writeFileSync(out, lines.join('\n'));
console.log('bars', bars.map(firstX), 'dots', dots.map((d) => firstX(d.d)), 'letters', letters.map((l) => `${firstX(l.d)}${navy(l.fill) ? 'N' : 'O'}`));
